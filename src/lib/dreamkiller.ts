/**
 * 倒されたときに言い残す言葉。
 *
 * **毎回ちがう言い方にする。**（同じ文が3回続くと、演出ではなく仕掛けに見える）
 * ただし言う中身＝芯は変えない。芯が抜けたら、下の固定文に差し替える（hasCore）。
 * これが「方向性は同じ、でも定型文は嫌」への答え。
 */
export const SURRENDER_CORE = [
  { name: "投影", re: /うつし|映し|うつ(し|って)|投影|きみの(心|こころ)の(なか|中)/ },
  { name: "言い返せた＝信じている", re: /信じ/ },
  { name: "ありがとう", re: /ありがと/ },
] as const;

/** 芯が3つとも入っているか（1つでも欠けたら固定文に戻す） */
export function hasCore(text: string): boolean {
  return SURRENDER_CORE.every((c) => c.re.test(text));
}

