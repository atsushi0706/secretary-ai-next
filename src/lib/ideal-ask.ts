/** この決まりを配るワーク（理想の世界に立たせるもの） */
export const IDEAL_MODES = ["peak", "walk", "travel", "breakthrough", "higher", "crystal"] as const;

export function usesIdealAsk(mode: string): boolean {
  return (IDEAL_MODES as readonly string[]).includes(mode);
}

/* ══ 締めの問いを、コードで見張る ═══════════════════════════════
 * 決まりを書いても、AIは「どんなふうに見えてる？」に戻ってしまう。
 * 淳くん：「問いかけられると、その方向の答えを見ちゃう。大体は捏造になる」
 * だから**返事を検査して、駄目な締めは動きの問いに置き換える**。
 */

/** こちらが答えの方向を決めてしまっている問い */
const BAD_CLOSER = [
  /どんな(ふう|風|感じ)に[^。？?]*(見え|聞こえ|伝わ|感じ|映|流れ)/,
  /どんな(景色|音|匂い|におい|空気|風|色|光|表情|顔)[^。？?]*(が|は)?[^。？?]*(見え|聞こえ|する|ある|吹|流れ)/,
  /何が(見え|聞こえ)(る|てる|ますか)/,
  /どう(見え|聞こえ|映っ)(る|てる)/,
];

/** 置き換える先。動き・欲のほうへ向ける（毎回同じにしない） */
export const MOVE_CLOSERS = [
  "そこで、何がしたくなってくる？",
  "そこで、いま何してる？",
  "そのあと、さらにどうしたい？",
  "もっと欲張っていいよ。次は何する？",
  "そこで、まず何からやってる？",
  "そこから、どう動く？",
] as const;

/** 文末の問いだけを取り出す（？で終わる最後のひとかたまり） */
export function lastQuestion(text: string): string {
  const t = String(text ?? "").trim();
  const m = t.match(/[^。！\n？?]*[？?]\s*$/);
  return m ? m[0].trim() : "";
}

export function isBadCloser(q: string): boolean {
  return !!q && BAD_CLOSER.some((re) => re.test(q));
}

/**
 * 締めが「答えの方向を決めている問い」なら、動きの問いに差し替える。
 * seed は「毎回同じ文にしない」ためだけに使う。
 */
export function fixCloser(text: string, seed: number): string {
  const t = String(text ?? "");
  const q = lastQuestion(t);
  if (!isBadCloser(q)) return t;
  const pick = MOVE_CLOSERS[Math.abs(Math.trunc(seed)) % MOVE_CLOSERS.length];
  return (t.slice(0, t.length - q.length).trimEnd() + " " + pick).trim();
}
