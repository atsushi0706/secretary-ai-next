/** この決まりを配るワーク（理想の世界に立たせるもの） */
export const IDEAL_MODES = ["peak", "walk", "travel", "breakthrough", "higher", "crystal"] as const;

export function usesIdealAsk(mode: string): boolean {
  return (IDEAL_MODES as readonly string[]).includes(mode);
}

/* ══ 会話はいじらない。見ているだけ ══════════════════════
 * ここには前まで、リンクの出した問いを**書き換える**仕組みがあった。
 * 飾りを聞いて締めていたら、その一文を落としたり、用意した文に差し替えたりしていた。
 *
 * それも結局、「どの問いが良いか」を僕が決めているということ。
 * 淳くん：「問いの方向性は指定しないで」——書き換えも指定のうち。
 *
 * だからやめた。**会話は通す。**
 * 代わりに、飾りを聞いて締めた回数だけ数えて記録に残す。
 * 場の渡し方（IDEAL_ASK）で足りているのかどうかを、こちらが確かめるため。
 * 直すのは、記録を見てから。
 */

/**
 * 「どんな◯◯が」と、こちらが中身を名指しした問い。
 *
 * 「何が見える？」は数えない——開いているので、見る先を決めるのは相手。
 * 数えるのは「どんな香りが」「どんな景色が」のように、
 * こちらが先に枠を置いてしまっているものだけ（淳くんの線引き）。
 */
const DECOR = /(景色|音|匂い|におい|香り|空気|風|色|光|味|感触|手ざわり|手触り|床|温度)/;

/** 文末の問いだけを取り出す（？で終わる最後のひとかたまり） */
export function lastQuestion(text: string): string {
  const t = String(text ?? "").trim();
  const m = t.match(new RegExp("[^。！" + String.fromCharCode(10) + "？?]*[？?]\\s*$"));
  return m ? m[0].trim() : "";
}

/** 飾りで締めているか（数えるためだけに使う。会話は変えない） */
export function isDecorCloser(q: string): boolean {
  if (!q) return false;
  if (/(胸|みぞおち|お腹|肩|喉|背中|足の裏|体のどこ)/.test(q)) return false;   // 体に戻すのは飾りではない
  return /どんな/.test(q) && DECOR.test(q);
}
