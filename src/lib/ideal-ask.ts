/** この決まりを配るワーク（理想の世界に立たせるもの） */
export const IDEAL_MODES = ["peak", "walk", "travel", "breakthrough", "higher", "crystal"] as const;

export function usesIdealAsk(mode: string): boolean {
  return (IDEAL_MODES as readonly string[]).includes(mode);
}

/* ══ 名指しで頼まれた2つだけ、コードでも止める ══════════════
 * 問いの方向をこちらが決めるのはやめた（見本も、書き換えもやめた）。
 * ただし淳くんが**何度も名指しで**やめてほしいと言ったものが2つある。
 *
 *   ① 自分の顔・表情を聞く……「ヘルメットの中でどんな顔してる？」
 *      淳くん：「マジで人生に関係なくてどうでもいい」
 *   ② 前の話題を引っぱり戻す……別の話をしているのに「またバイクが…」
 *      淳くん：「本当に煩わしい。いちいち『引っ張らなくていい』と言うのも煩わしい」
 *
 * 場の渡し方（IDEAL_ASK）だけでは4回止まらなかった。だからここで止める。
 * ただし**置き換えない。その一文を落とすだけ**（決まり文句を並べたら本末転倒）。
 * 問いの無い返事になってもいい。この場では、そのほうが合っている。
 */

/** 文末の問いだけを取り出す（？で終わる最後のひとかたまり） */
export function lastQuestion(text: string): string {
  const t = String(text ?? "").trim();
  const m = t.match(new RegExp("[^。！" + String.fromCharCode(10) + "？?]*[？?]\\s*$"));
  return m ? m[0].trim() : "";
}

/** ① 自分の顔・表情を聞いている */
export function isFaceCloser(q: string): boolean {
  return !!q && /(顔|表情)/.test(q);
}

/** どこにでも出てくる言葉。引きずりの目印にしない */
const COMMON = new Set([
  "自分", "気持", "感じ", "感覚", "状態", "時間", "今日", "明日", "昨日", "世界", "理想",
  "仕事", "本当", "一番", "最高", "場所", "瞬間", "自由", "毎日", "全部", "普通", "大事",
  "人生", "現実", "気分", "自身", "相手", "自然", "一緒", "本当に",
]);

/** 文章から、目印になりそうな言葉を拾う（2文字以上のカタカナ・漢字） */
export function keywordsOf(text: string): string[] {
  const out = String(text ?? "").match(/[ァ-ヴー]{2,}|[一-龥]{2,}/g) ?? [];
  return [...new Set(out.filter((w) => !COMMON.has(w)))];
}

/**
 * ② 前の話題を引っぱり戻している。
 * いま相手が言っていない言葉なのに、**前のほうの話**から持ってきて問いに入れている。
 */
export function draggedCloser(q: string, lastSaid: string, older: string): boolean {
  if (!q) return false;
  const now = new Set(keywordsOf(lastSaid));
  const back = new Set(keywordsOf(older));
  return keywordsOf(q).some((w) => !now.has(w) && back.has(w));
}

/** 落とす理由（記録に残す用）。落とさないなら null */
export function closerToDrop(text: string, lastSaid: string, older: string): "face" | "dragged" | null {
  const q = lastQuestion(text);
  if (!q) return null;
  if (isFaceCloser(q)) return "face";
  if (draggedCloser(q, lastSaid, older)) return "dragged";
  return null;
}

/** その一文を落とす（置き換えない） */
export function dropCloser(text: string): string {
  const q = lastQuestion(text);
  if (!q) return text;
  return text.slice(0, text.length - q.length).trimEnd();
}
