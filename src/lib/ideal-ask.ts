/** この決まりを配るワーク（理想の世界に立たせるもの） */
export const IDEAL_MODES = ["peak", "walk", "travel", "breakthrough", "higher", "crystal"] as const;

export function usesIdealAsk(mode: string): boolean {
  return (IDEAL_MODES as readonly string[]).includes(mode);
}

/* ══ 締めの問いの、最後の砦 ════════════════════════════════
 * 場の説明（IDEAL_ASK）で足りるのが本来。ここは**本当に壊れるものだけ**を止める。
 *
 * 止めるのはひとつ、「飾りを聞いて締める」形。
 *   「窓の外にはどんな景色が広がってる？」「どんな香りがする？」「どんな感触の床？」
 * これをやられると、こちらが決めた枠を埋めに行くことになる（淳くんが何度も指摘）。
 *
 * 【前はどうしていたか／なぜ変えたか】
 * 見つけたら、用意した6つの文のどれかに**置き換えて**いた。
 * それだと今度はこちらの決まり文句が並ぶ。淳くん：「ワンパターンすぎる」。
 * だから置き換えない。**その一文を落とすだけ**にする。
 * 問いが無い返事になってもいい（問いは減らすほうが、この場には合っている）。
 */

/** 飾りを聞いている問い。動きではなく、世界の中身をこちらが決めている */
const DECOR = /(景色|音|匂い|におい|香り|空気|風|色|光|味|感触|手ざわり|手触り|床|温度)/;

/** 文末の問いだけを取り出す（？で終わる最後のひとかたまり） */
export function lastQuestion(text: string): string {
  const t = String(text ?? "").trim();
  const m = t.match(new RegExp("[^。！" + String.fromCharCode(10) + "？?]*[？?]\s*$"));
  return m ? m[0].trim() : "";
}

export function isBadCloser(q: string): boolean {
  if (!q) return false;
  // 「体のどこ」に向けているものは通す（体に戻すのは、飾りではない）
  if (/(胸|みぞおち|お腹|肩|喉|背中|足の裏|体のどこ)/.test(q)) return false;
  return /どんな/.test(q) && DECOR.test(q);
}

/**
 * 飾りで締めていたら、その一文を落とす。置き換えはしない。
 * seed は使わない（残してあるのは、呼び出し側を壊さないため）。
 */
export function fixCloser(text: string, _seed?: number): string {
  const t = String(text ?? "");
  const q = lastQuestion(t);
  if (!isBadCloser(q)) return t;
  return t.slice(0, t.length - q.length).trimEnd();
}
