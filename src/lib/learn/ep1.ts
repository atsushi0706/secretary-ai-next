const T = (id: string, text: string, extra: Partial<Line> = {}): Line => ({ id, who: "teacher", text, ...extra });
const L = (id: string, text: string, extra: Partial<Line> = {}): Line => ({ id, who: "link", text, ...extra });
const S = (slide: Slide): Slide => slide;

function channelBranch(
  id: string,
  acknowledgement: string,
  suggestion: string,
  linkLine: string,
  close: string,
): ExpStep[] {
  return [
    { kind: "say", line: T(`${id}-1`, acknowledgement) },
    { kind: "say", line: T(`${id}-2`, suggestion) },
    { kind: "say", line: L(`${id}-3`, linkLine, { face: "aha" }) },
    { kind: "say", line: T(`${id}-4`, close, { face: "smile" }) },
    { kind: "fade", text: "足の事件へ戻る" },
  ];
}

