/**
 * ワークに入る瞬間に見せる「これは何をする場所か」。
 *
 * 名前だけ大きく出しても、初めての人には何も伝わらない。
 * かといって説明書を読ませたら、その時点でもう体験ではなくなる。
 *
 * だから **短い3行** にした。
 *   ・poem  … その世界の情景（感覚に入れる）
 *   ・what  … 何をする場所なのか（一言）
 *   ・why   … 何のためなのか（意図）
 * 声に出して2〜3秒で読み切れる長さに収める。読みたくない人はタップで飛ばせる。
 *
 * 言葉づかいの決まり：
 *   ・説明くさくしない。「〜する機能です」と書かない
 *   ・専門用語（算命学・パーツ心理学など）は出さない
 *   ・淳くんがくれた定義を芯にする
 */
