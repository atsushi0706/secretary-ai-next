/**
 * ワークの進め方をプロンプトにする。
 *
 * 段階制のワーク（ウォールブレイク）では、**いま立っている段階の1枚だけ**を渡す。
 * 5段階ぶんをまとめて渡すと、AIは終わりまで見えてしまうので、
 * 陰を2〜3個聞いたところで統合点まで走ってしまう。それではこのワークは効かない。
 */
export function buildModePrompt(mode: ModeKey, stage?: number | null): string {
  const m = MODES[mode];
  if (!m) return "";
  const parts = [m.flow];
  if (m.stages) {
    const keys = Object.keys(m.stages).map(Number).sort((a, b) => a - b);
    const cur = Math.max(keys[0], Math.min(keys[keys.length - 1], Number(stage) || keys[0]));
    parts.push(m.stages[cur]);
  }
  parts.push(GUIDANCE);
  return parts.join("\n\n");
}
