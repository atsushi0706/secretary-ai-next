export const MODE_KEYS = Object.keys(MODES) as ModeKey[];

export function isModeKey(v: unknown): v is ModeKey {
  return typeof v === "string" && v in MODES;
}

const GUIDANCE = `
# 進め方（枠にはめない）
- 「セッション」という枠で考えない。決まった順で質問攻めにしない。相手が好きに話せるように。
- ただし分かれ道では、案内役から選択肢をボタンで出す。相手が選びやすいように。
  次に選べるものがあるとき、返事の最後にこのタグを付ける（本文には書かない）:
  <choices>[{"label":"パラレルウォーク行く","mode":"walk"},{"label":"今日の流れを見る","mode":"akashic"}]</choices>
  - mode を付けると、その場所へ移動して、そのワークが始まる。
  - mode を付けず label だけなら、その言葉を相手が答えたことになる（「はい」「まだ大丈夫」など）。
  - 選択肢は2〜3個まで。毎回は出さない。自然な分かれ道でだけ。
- 質問は基本1つずつ。畳みかけない。相手が黙っても急かさない。
`.trim();

/** 案内役に渡す、このゾーンぶんの追加指示 */
export function buildModePrompt(mode: ModeKey): string {
  const m = MODES[mode];
  if (!m) return "";
  return [m.flow, GUIDANCE].join("\n\n");
}
