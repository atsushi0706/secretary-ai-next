export function isShadowPairId(v: unknown): v is ShadowPairId {
  return typeof v === "string" && SHADOW_PAIRS.some((p) => p.id === v);
}
export function shadowPair(id: ShadowPairId): ShadowPair {
  return SHADOW_PAIRS.find((p) => p.id === id)!;
}

