/** ホームの見立てに渡す一覧（開いている部屋だけ） */
export function guideListFor(open: ModeKey[]): string {
  return open
    .map((k) => {
      const g = WORK_GUIDE[k];
      if (!g) return null;
      return `- ${k}：${g.oneLine}\n  こういうときに来る場所：${g.when}`;
    })
    .filter(Boolean)
    .join("\n");
}
