/**
 * 音声に渡す直前の「読みなおし」。
 *
 * 音声合成は数字を素直に読むので、「1回目」は「いち・かいめ」になる。
 * 日本語では「いっかいめ」。こういう促音・撥音の変化は合成側では直せないので、
 * **こちらでかなに書き換えてから渡す**。
 *
 * ここを通すのは「耳に届く文」だけ。画面の文字は元のまま（1回目）でよい。
 */

/** 数字＋助数詞の、実際の読み。促音化・半濁音化するものだけ並べる */
const COUNTERS: { suffix: string; yomi: string[] }[] = [
  // 回：いっかい / さんかい / ろっかい / はっかい / じゅっかい
  { suffix: "回", yomi: ["", "いっかい", "にかい", "さんかい", "よんかい", "ごかい", "ろっかい", "ななかい", "はっかい", "きゅうかい", "じゅっかい"] },
  // 分：いっぷん / さんぷん / よんぷん …
  { suffix: "分", yomi: ["", "いっぷん", "にふん", "さんぷん", "よんぷん", "ごふん", "ろっぷん", "ななふん", "はっぷん", "きゅうふん", "じゅっぷん"] },
  // 秒：ふつうに読めるが、そろえておく
  { suffix: "秒", yomi: ["", "いちびょう", "にびょう", "さんびょう", "よんびょう", "ごびょう", "ろくびょう", "ななびょう", "はちびょう", "きゅうびょう", "じゅうびょう"] },
  // 本：いっぽん / さんぼん / ろっぽん …
  { suffix: "本", yomi: ["", "いっぽん", "にほん", "さんぼん", "よんほん", "ごほん", "ろっぽん", "ななほん", "はっぽん", "きゅうほん", "じゅっぽん"] },
  // 人：ひとり / ふたり から始まる
  { suffix: "人", yomi: ["", "ひとり", "ふたり", "さんにん", "よにん", "ごにん", "ろくにん", "しちにん", "はちにん", "きゅうにん", "じゅうにん"] },
  // 歳：いっさい / はっさい / じゅっさい
  { suffix: "歳", yomi: ["", "いっさい", "にさい", "さんさい", "よんさい", "ごさい", "ろくさい", "ななさい", "はっさい", "きゅうさい", "じゅっさい"] },
  // 日（〜日間の意味ではなく「◯日目」で使う想定）
  { suffix: "日", yomi: ["", "いちにち", "ふつか", "みっか", "よっか", "いつか", "むいか", "なのか", "ようか", "ここのか", "とおか"] },
];

/** 個別の言い換え（合成が苦手な語だけ、必要になったら足す） */
const WORDS: [RegExp, string][] = [
  [/一回/g, "いっかい"],
  [/1度/g, "いちど"],
  [/今日/g, "きょう"],      // 「こんにち」と読まれることがある
  [/一日/g, "いちにち"],
  [/1つ/g, "ひとつ"],
  [/2つ/g, "ふたつ"],
  [/3つ/g, "みっつ"],
];

/**
 * 耳に届く文にする。
 *  1. 絵文字と記号（**、#、—など）を落とす … そのまま読み上げたり、変な間になる
 *  2. 数字＋助数詞を、実際の読みのかなに置き換える
 *  3. 個別の言い換え
 */
export function toYomi(input: string): string {
  let t = input;

  // ① 絵文字・装飾記号（読み上げの邪魔になるものだけ）
  t = t.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{2190}-\u{21FF}]/gu, "");
  t = t.replace(/[*_#`>|~]/g, "");

  // ② 数字＋助数詞（半角・全角どちらも）
  const z2h = (s: string) => s.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
  for (const { suffix, yomi } of COUNTERS) {
    t = t.replace(new RegExp(`([0-9０-９]+)${suffix}`, "g"), (whole, numRaw: string) => {
      const n = Number(z2h(numRaw));
      return Number.isInteger(n) && n >= 1 && n <= 10 && yomi[n] ? yomi[n] : whole;
    });
  }

  // ③ 個別
  for (const [re, to] of WORDS) t = t.replace(re, to);

  return t.replace(/\s+/g, " ").trim();
}
